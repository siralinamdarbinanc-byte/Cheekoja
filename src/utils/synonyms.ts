/**
 * Gets expanded search terms for a given query string using synonym dictionary
 */
export function getExpandedSearchTerms(query: string): string[] {
  if (!query || !query.trim()) return [];

  const normalized = query.trim().toLowerCase();
  const words = normalized.split(/\s+/);
  const terms = new Set<string>([normalized, ...words]);

  words.forEach((word) => {
    Object.keys(PERSIAN_SYNONYMS).forEach((key) => {
      if (key.includes(word) || word.includes(key)) {
        PERSIAN_SYNONYMS[key].forEach((syn) => terms.add(syn));
      }
    });
  });

  return Array.from(terms);
}
